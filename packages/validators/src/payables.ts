import {
  compareDecimals,
  isValidBankCode,
  isValidIdDocument,
  isValidMobilePhone,
  normalizeIdDocument,
  normalizeMobilePhone,
  PAYABLE_PAYMENT_METHODS,
  PAYABLE_STATUSES,
  PAYABLE_UNITS,
  PURCHASE_UNITS,
} from "@ta/core";
import { z } from "zod";

import { decimalSchema } from "./amount";
import { currencySchema } from "./daily-closes";
import { businessDateSchema, rateValueSchema } from "./exchange-rates";
import { message } from "./messages";
import { paginatedSchema, paginationQuerySchema } from "./pagination";
import { supplierSchema } from "./purchases";

/*
 * Payables: supplier invoices on credit, their lines and payments, and the suppliers' pago móvil
 * accounts (docs/modules/payables.md). Amounts are decimal strings in the invoice's currency;
 * the API computes subtotals, balances and statuses with @ta/core. Messages are tokens.
 */

export const payableUnitSchema = z.enum(PAYABLE_UNITS);
export const payablePaymentMethodSchema = z.enum(PAYABLE_PAYMENT_METHODS, {
  error: message("payable.methodRequired"),
});
export const payableStatusSchema = z.enum(PAYABLE_STATUSES);

const shortText = (max: number) =>
  z
    .string()
    .transform((v) => v.trim())
    .pipe(z.string().max(max, message("text.tooLong", { max })));

/** Trimmed; an empty text is the same as none (a cleared form field). */
const optionalText = (max: number) =>
  z.preprocess(
    (v) => (typeof v === "string" && v.trim() === "" ? undefined : v),
    shortText(max).optional(),
  );

const positive = (subject: "amount" | "quantity") =>
  decimalSchema(subject).refine((v) => compareDecimals(v, "0") > 0, {
    message: message("decimal.positive", { subject }),
  });

// Supplier pago móvil accounts -----------------------------------------------------------------

/** A supplier's pago móvil account; phone and cédula are stored as the banks want them. */
export const supplierPaymentAccountInputSchema = z.object({
  bankCode: z
    .string({ error: message("mobilePayment.bankInvalid") })
    .refine(isValidBankCode, message("mobilePayment.bankInvalid")),
  phone: z
    .string({ error: message("mobilePayment.phoneInvalid") })
    .transform(normalizeMobilePhone)
    .refine(isValidMobilePhone, message("mobilePayment.phoneInvalid")),
  idDocument: z
    .string({ error: message("mobilePayment.idDocumentInvalid") })
    .transform(normalizeIdDocument)
    .refine(isValidIdDocument, message("mobilePayment.idDocumentInvalid")),
});

export type SupplierPaymentAccountInput = z.input<typeof supplierPaymentAccountInputSchema>;
export type SupplierPaymentAccountFields = z.output<typeof supplierPaymentAccountInputSchema>;

// Invoices ---------------------------------------------------------------------------------------

/**
 * A line of a manual invoice: a supply or expense (bags, bread…) with its expense category.
 * Merchandise never goes here: it is bought with the purchase form (a local purchase or a Coche
 * trip line on credit), which prices it and creates the invoice (docs/modules/payables.md).
 */
export const payableLineInputSchema = z.object({
  description: z
    .string({ error: message("payable.descriptionRequired") })
    .transform((v) => v.trim().replace(/\s+/g, " "))
    .pipe(
      z
        .string()
        .min(1, message("payable.descriptionRequired"))
        .max(80, message("text.tooLong", { max: 80 })),
    ),
  expenseCategoryId: z.uuid({ error: message("payable.categoryRequired") }),
  quantity: positive("quantity"),
  unit: payableUnitSchema,
  unitPrice: decimalSchema("price"),
});

export type PayableLineInput = z.input<typeof payableLineInputSchema>;

/**
 * POST /api/v1/payables (and PATCH, which replaces the contents while it has no payments).
 * The code (CXP-000123) is generated by the API.
 */
export const payableInputSchema = z
  .object({
    supplierId: z.uuid({ error: message("payable.supplierRequired") }),
    /** As agreed with the supplier; lines, total and balance are in this currency. */
    currency: currencySchema.default("USD"),
    issuedOn: businessDateSchema,
    dueOn: businessDateSchema,
    note: optionalText(200),
    lines: z
      .array(payableLineInputSchema)
      .min(1, message("payable.linesRequired"))
      .max(50, message("payable.tooManyLines", { max: 50 })),
  })
  .refine((v) => v.dueOn >= v.issuedOn, {
    message: message("payable.dueBeforeIssue"),
    path: ["dueOn"],
  });

export type PayableInput = z.input<typeof payableInputSchema>;
export type PayableFields = z.output<typeof payableInputSchema>;

// Payments ---------------------------------------------------------------------------------------

/**
 * POST /api/v1/payables/:id/payments. The currency comes from the method; `rate` is the BCV
 * rate of the payment day (the form suggests it). Paying more than the balance is a rule
 * error (PAYMENT_EXCEEDS_BALANCE, @ta/core `settlePayment`).
 */
export const payablePaymentInputSchema = z.object({
  paidOn: businessDateSchema,
  method: payablePaymentMethodSchema,
  amount: positive("amount"),
  rate: rateValueSchema,
  /** Pago móvil or transfer reference. */
  reference: optionalText(30),
  /** The supplier's account it was sent to; "" (no account chosen) is none. */
  accountId: z.preprocess((v) => (v === "" ? undefined : v), z.uuid().optional()),
  note: optionalText(200),
});

export type PayablePaymentInput = z.input<typeof payablePaymentInputSchema>;
export type PayablePaymentFields = z.output<typeof payablePaymentInputSchema>;

// Queries --------------------------------------------------------------------------------------

export const payableListQuerySchema = paginationQuerySchema.extend({
  status: payableStatusSchema.optional(),
  supplierId: z.uuid().optional(),
});

export type PayableListQueryInput = z.input<typeof payableListQuerySchema>;
export type PayableListQuery = z.output<typeof payableListQuerySchema>;

/**
 * PATCH /api/v1/payables/:id/terms — due date and note of any invoice that is not voided (an
 * invoice created from a Coche trip gets its due date here).
 */
export const payableTermsInputSchema = z.object({
  dueOn: businessDateSchema,
  note: optionalText(200),
});

export type PayableTermsInput = z.input<typeof payableTermsInputSchema>;
export type PayableTerms = z.output<typeof payableTermsInputSchema>;

// Responses ------------------------------------------------------------------------------------

export const supplierPaymentAccountSchema = z.object({
  id: z.uuid(),
  bankCode: z.string(),
  bankName: z.string(),
  phone: z.string(),
  idDocument: z.string(),
  isActive: z.boolean(),
});

export type SupplierPaymentAccount = z.infer<typeof supplierPaymentAccountSchema>;

export const supplierDetailSchema = supplierSchema.extend({
  accounts: z.array(supplierPaymentAccountSchema),
});

export type SupplierDetail = z.infer<typeof supplierDetailSchema>;

const totalsSchema = z.object({ USD: z.string(), VES: z.string() });

export const payableSummarySchema = z.object({
  id: z.uuid(),
  /** CXP-000123 */
  code: z.string(),
  supplierId: z.uuid(),
  supplierName: z.string(),
  currency: currencySchema,
  total: z.string(),
  paid: z.string(),
  balance: z.string(),
  issuedOn: z.string(),
  dueOn: z.string().nullable(),
  status: payableStatusSchema,
  tripId: z.uuid().nullable(),
});

export type PayableSummary = z.infer<typeof payableSummarySchema>;

export const payableListSchema = paginatedSchema(payableSummarySchema).extend({
  /** What is still owed by the invoices of the filter, per currency (all pages). */
  balance: totalsSchema,
});

export type PayableList = z.infer<typeof payableListSchema>;

/** A supply typed by the owner, or merchandise bought with the purchase form. */
export const payableLineSchema = z.object({
  id: z.uuid(),
  subtotal: z.string(),
  description: z.string().nullable(),
  expenseCategoryId: z.uuid().nullable(),
  expenseCategoryName: z.string().nullable(),
  quantity: z.string().nullable(),
  unit: payableUnitSchema.nullable(),
  unitPrice: z.string().nullable(),
  purchaseLine: z
    .object({
      id: z.uuid(),
      productId: z.uuid(),
      productName: z.string(),
      purchaseUnit: z.enum(PURCHASE_UNITS),
      packs: z.string().nullable(),
      grossQuantity: z.string(),
    })
    .nullable(),
});

export type PayableLine = z.infer<typeof payableLineSchema>;

export const payablePaymentSchema = z.object({
  id: z.uuid(),
  paidOn: z.string(),
  method: payablePaymentMethodSchema,
  currency: currencySchema,
  amountUsd: z.string(),
  amountBs: z.string(),
  rate: z.string(),
  applied: z.string(),
  reference: z.string().nullable(),
  accountId: z.uuid().nullable(),
  note: z.string().nullable(),
  createdAt: z.string(),
});

export type PayablePayment = z.infer<typeof payablePaymentSchema>;

export const payableDetailSchema = payableSummarySchema.extend({
  note: z.string().nullable(),
  voidedAt: z.string().nullable(),
  lines: z.array(payableLineSchema),
  payments: z.array(payablePaymentSchema),
});

export type PayableDetail = z.infer<typeof payableDetailSchema>;

/**
 * GET /api/v1/payables/:id/mobile-payment — what to pay today by pago móvil: the balance in Bs
 * (a USD invoice at today's BCV rate) and, per active account, the text for "Pegar datos".
 */
export const mobilePaymentDataSchema = z.object({
  businessDate: z.string(),
  currency: currencySchema,
  balance: z.string(),
  /** Null for a Bs invoice (the amount is fixed). */
  bcvRate: z.string().nullable(),
  /** 2 decimals, "." separator. */
  amountBs: z.string(),
  /** As the banks read it: "1234,56". */
  amountText: z.string(),
  accounts: z.array(supplierPaymentAccountSchema.extend({ clipboard: z.string() })),
});

export type MobilePaymentData = z.infer<typeof mobilePaymentDataSchema>;

export const expenseCategorySchema = z.object({
  id: z.uuid(),
  code: z.string(),
  name: z.string(),
  kind: z.enum(["fixed", "variable"]),
});

export type ExpenseCategory = z.infer<typeof expenseCategorySchema>;
export const expenseCategoryListSchema = z.object({ data: z.array(expenseCategorySchema) });
