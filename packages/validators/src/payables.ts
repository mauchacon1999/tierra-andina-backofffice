import {
  compareDecimals,
  isValidBankCode,
  isValidIdDocument,
  isValidMobilePhone,
  normalizeIdDocument,
  normalizeMobilePhone,
  PAYABLE_PAYMENT_METHODS,
  PAYABLE_STATUSES,
  PAYABLE_UNITS,
} from "@ta/core";
import { z } from "zod";

import { decimalSchema } from "./amount";
import { currencySchema } from "./daily-closes";
import { businessDateSchema, rateValueSchema } from "./exchange-rates";
import { message } from "./messages";

/*
 * Payables: supplier invoices on credit, their lines and payments, and the suppliers' pago móvil
 * accounts (docs/modules/payables.md). Amounts are decimal strings in the invoice's currency;
 * the API computes subtotals, balances and statuses with @ta/core. Messages are tokens.
 */

export const payableUnitSchema = z.enum(PAYABLE_UNITS);
export const payablePaymentMethodSchema = z.enum(PAYABLE_PAYMENT_METHODS, {
  error: message("payable.methodRequired"),
});
export const payableStatusSchema = z.enum(PAYABLE_STATUSES);

const shortText = (max: number) =>
  z
    .string()
    .transform((v) => v.trim())
    .pipe(z.string().max(max, message("text.tooLong", { max })));

/** Trimmed; an empty text is the same as none (a cleared form field). */
const optionalText = (max: number) =>
  z.preprocess(
    (v) => (typeof v === "string" && v.trim() === "" ? undefined : v),
    shortText(max).optional(),
  );

const positive = (subject: "amount" | "quantity") =>
  decimalSchema(subject).refine((v) => compareDecimals(v, "0") > 0, {
    message: message("decimal.positive", { subject }),
  });

// Supplier pago móvil accounts -----------------------------------------------------------------

/** A supplier's pago móvil account; phone and cédula are stored as the banks want them. */
export const supplierPaymentAccountInputSchema = z.object({
  bankCode: z
    .string({ error: message("mobilePayment.bankInvalid") })
    .refine(isValidBankCode, message("mobilePayment.bankInvalid")),
  phone: z
    .string({ error: message("mobilePayment.phoneInvalid") })
    .transform(normalizeMobilePhone)
    .refine(isValidMobilePhone, message("mobilePayment.phoneInvalid")),
  idDocument: z
    .string({ error: message("mobilePayment.idDocumentInvalid") })
    .transform(normalizeIdDocument)
    .refine(isValidIdDocument, message("mobilePayment.idDocumentInvalid")),
});

export type SupplierPaymentAccountInput = z.input<typeof supplierPaymentAccountInputSchema>;
export type SupplierPaymentAccountFields = z.output<typeof supplierPaymentAccountInputSchema>;

// Invoices ---------------------------------------------------------------------------------------

/**
 * A line of a manual invoice: a supply or expense (bags, bread…) with its expense category.
 * Merchandise never goes here: it is bought with the purchase form (a local purchase or a Coche
 * trip line on credit), which prices it and creates the invoice (docs/modules/payables.md).
 */
export const payableLineInputSchema = z.object({
  description: z
    .string({ error: message("payable.descriptionRequired") })
    .transform((v) => v.trim().replace(/\s+/g, " "))
    .pipe(
      z
        .string()
        .min(1, message("payable.descriptionRequired"))
        .max(80, message("text.tooLong", { max: 80 })),
    ),
  expenseCategoryId: z.uuid({ error: message("payable.categoryRequired") }),
  quantity: positive("quantity"),
  unit: payableUnitSchema,
  unitPrice: decimalSchema("price"),
});

export type PayableLineInput = z.input<typeof payableLineInputSchema>;

/**
 * POST /api/v1/payables (and PATCH, which replaces the contents while it has no payments).
 * The code (CXP-000123) is generated by the API.
 */
export const payableInputSchema = z
  .object({
    supplierId: z.uuid({ error: message("payable.supplierRequired") }),
    /** As agreed with the supplier; lines, total and balance are in this currency. */
    currency: currencySchema.default("USD"),
    issuedOn: businessDateSchema,
    dueOn: businessDateSchema,
    note: optionalText(200),
    lines: z
      .array(payableLineInputSchema)
      .min(1, message("payable.linesRequired"))
      .max(50, message("payable.tooManyLines", { max: 50 })),
  })
  .refine((v) => v.dueOn >= v.issuedOn, {
    message: message("payable.dueBeforeIssue"),
    path: ["dueOn"],
  });

export type PayableInput = z.input<typeof payableInputSchema>;
export type PayableFields = z.output<typeof payableInputSchema>;

// Payments ---------------------------------------------------------------------------------------

/**
 * POST /api/v1/payables/:id/payments. The currency comes from the method; `rate` is the BCV
 * rate of the payment day (the form suggests it). Paying more than the balance is a rule
 * error (PAYMENT_EXCEEDS_BALANCE, @ta/core `settlePayment`).
 */
export const payablePaymentInputSchema = z.object({
  paidOn: businessDateSchema,
  method: payablePaymentMethodSchema,
  amount: positive("amount"),
  rate: rateValueSchema,
  /** Pago móvil or transfer reference. */
  reference: optionalText(30),
  /** The supplier's account it was sent to. */
  accountId: z.uuid().optional(),
  note: optionalText(200),
});

export type PayablePaymentInput = z.input<typeof payablePaymentInputSchema>;
export type PayablePaymentFields = z.output<typeof payablePaymentInputSchema>;
